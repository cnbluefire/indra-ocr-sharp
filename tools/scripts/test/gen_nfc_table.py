"""Generate the NFC tables (step 295) from Python's ``unicodedata``.

``indra_ocr/vocab.py`` normalises a label with ``unicodedata.normalize("NFC", text)``, and the
port cannot use ``string.Normalize`` for it: with ``InvariantGlobalization`` — which the AOT
builds want, so the native binary needs no ICU — .NET's normalisation is a no-op, and the port
would silently stop composing ``"e" + U+0301`` into ``"é"``.

So NFC is implemented in managed code from CPython's own tables (Unicode 16.0.0, the version the
reference's interpreter carries), which is also more faithful than ICU: the answer no longer
depends on the machine's ICU version, and unpaired surrogates pass through as they do in Python.

Three tables, all in code point order and all verified against ``unicodedata`` here:

* ``Decompositions`` — every canonical (not compatibility) decomposition, one or two code
  points, Hangul excluded because UAX #15 decomposes those algorithmically;
* ``Compositions`` — the primary composites, i.e. the pairs that compose back, which is the
  canonical decompositions of exactly two code points whose NFC of the pair is the composite
  itself;
* ``Combining`` — the non-zero canonical combining classes, as runs.

Run with the reference environment:

    tools\\pyenv\\Scripts\\python.exe tools\\scripts\\test\\gen_nfc_table.py
"""

from __future__ import annotations

import json
import unicodedata
from pathlib import Path

OUT_CS = Path("src/Indra.Ocr.Core/Text/NfcTables.cs")
OUT_JSON = Path("src/Indra.Ocr.Tests/fixtures/nfc.json")
MAX = 0x10FFFF
SBASE, SCOUNT = 0xAC00, 11172  # Hangul syllables: algorithmic, never in the table


def canonical_decompositions() -> list[tuple[int, int, int]]:
    """(code point, first, second) for every non-Hangul canonical decomposition."""
    table: list[tuple[int, int, int]] = []
    for cp in range(MAX + 1):
        if SBASE <= cp < SBASE + SCOUNT:
            continue
        decomposition = unicodedata.decomposition(chr(cp))
        if not decomposition or decomposition.startswith("<"):
            continue  # none, or a compatibility decomposition, which NFC does not use
        parts = [int(x, 16) for x in decomposition.split()]
        assert 1 <= len(parts) <= 2, (hex(cp), decomposition)
        table.append((cp, parts[0], parts[1] if len(parts) == 2 else 0))
    return table


def primary_composites(decompositions: list[tuple[int, int, int]]) -> list[tuple[int, int, int]]:
    """(first, second, composite) for every pair that composes back."""
    table: list[tuple[int, int, int]] = []
    for cp, first, second in decompositions:
        if second == 0:
            continue
        pair = chr(first) + chr(second)
        if unicodedata.normalize("NFC", pair) == chr(cp):
            table.append((first, second, cp))
    return sorted(table)


def combining_runs() -> list[tuple[int, int, int]]:
    """(first, last, class) runs of the code points whose canonical combining class is not 0."""
    runs: list[tuple[int, int, int]] = []
    for cp in range(MAX + 1):
        cls = unicodedata.combining(chr(cp))
        if cls == 0:
            continue
        if runs and runs[-1][1] == cp - 1 and runs[-1][2] == cls:
            runs[-1] = (runs[-1][0], cp, cls)
        else:
            runs.append((cp, cp, cls))
    return runs


def write_cs(decompositions, compositions, combining) -> None:
    lines = [
        "// <auto-generated>",
        "//     Generated by tools/scripts/test/gen_nfc_table.py from Python's unicodedata",
        f"//     (Unicode {unicodedata.unidata_version}).  Do not edit by hand:",
        "//     re-run the generator instead.",
        "// </auto-generated>",
        "",
        "namespace Indra.Ocr.Text;",
        "",
        "/// <summary>",
        "/// The tables of Unicode Normalization Form C (NFC), exactly as CPython's",
        "/// <c>unicodedata.normalize(\"NFC\", text)</c> reports them.  Hangul syllables are absent:",
        "/// UAX #15 decomposes and composes those arithmetically (<see cref=\"Nfc\"/>).",
        "/// </summary>",
        "internal static class NfcTables",
        "{",
        "    /// <summary>",
        "    /// Canonical decompositions in code point order: <c>(code point, first, second)</c>,",
        "    /// where <c>second</c> is 0 for a singleton.  The parts may decompose again — the",
        "    /// decomposition is applied recursively.",
        "    /// </summary>",
        "    internal static readonly (int Cp, int First, int Second)[] Decompositions =",
        "    [",
    ]
    lines += [f"        (0x{cp:04X}, 0x{first:04X}, 0x{second:04X})," for cp, first, second in decompositions]
    lines += [
        "    ];",
        "",
        "    /// <summary>",
        "    /// Primary composites in <c>(first, second)</c> order: <c>(first, second, composite)</c>.",
        "    /// </summary>",
        "    internal static readonly (int First, int Second, int Composite)[] Compositions =",
        "    [",
    ]
    lines += [f"        (0x{first:04X}, 0x{second:04X}, 0x{cp:04X})," for first, second, cp in compositions]
    lines += [
        "    ];",
        "",
        "    /// <summary>",
        "    /// The code points whose canonical combining class is not 0, as <c>(first, last,</c>",
        "    /// <c>class)</c> runs in code point order.  Everything else is 0.",
        "    /// </summary>",
        "    internal static readonly (int First, int Last, int Class)[] Combining =",
        "    [",
    ]
    lines += [f"        (0x{first:04X}, 0x{last:04X}, {cls})," for first, last, cls in combining]
    lines += ["    ];", "}", ""]
    OUT_CS.write_text("\n".join(lines), encoding="utf-8", newline="\n")


def cases(decompositions, compositions) -> tuple[list[list[str]], list[list[list[int]]]]:
    """The behavioural record: NFC inputs and CPython's answers.

    Two lists, because a lone surrogate is not a JSON string .NET will read back ("invalid
    surrogate value"): the ones that carry one are stored as code points instead.
    """
    out: list[list[str]] = []
    units: list[list[list[int]]] = []

    def add(text: str) -> None:
        expected = unicodedata.normalize("NFC", text)
        assert unicodedata.normalize("NFC", expected) == expected, repr(text)
        if any(0xD800 <= ord(c) <= 0xDFFF for c in text + expected):
            units.append([[ord(c) for c in text], [ord(c) for c in expected]])
        else:
            out.append([text, expected])

    # Every decomposition on its own (singletons and pairs) — the composition path.
    for cp, first, second in decompositions:
        add(chr(cp))
        add(chr(first) + (chr(second) if second else ""))
    # Every primary composite as the pair it comes from.
    for first, second, cp in compositions:
        add(chr(first) + chr(second))
        add(chr(cp))
    # Every Hangul syllable: algorithmic decomposition, then recomposition.
    for cp in range(SBASE, SBASE + SCOUNT):
        add(chr(cp))
    # Random strings over an alphabet that actually decomposes and combines: starters,
    # combining marks of several classes, jamo, Hangul, and a few supplementary-plane
    # characters with canonical decompositions.
    alphabet = (
        "aeiouyAEIOUY"
        "\u0300\u0301\u0302\u0303\u0308\u030A\u0323\u0327\u0328\u0334\u0345\u031B"
        "\u1100\u1102\u1161\u1162\u11A8\u11C2\uAC00\uD7A3\u00C5\u212B\u0958\u09CB"
        "\U0001D157\U0001D165\U0001D15E\u1E14\u0112\u0041\u0020\u002E\u4E00\uF900"
    )
    for seed in range(4000):
        state = seed * 6364136223846793005 + 1442695040888963407
        length = state % 12
        text = ""
        for _ in range(length):
            state = state * 6364136223846793005 + 1442695040888963407
            text += alphabet[(state >> 33) % len(alphabet)]
        add(text)
    # Random code points anywhere (surrogates included: Python passes them through, and so
    # must the port), which exercises the "nothing in the table" path.
    for seed in range(4000):
        state = seed * 2862933555777941757 + 3037000493
        text = ""
        for _ in range(state % 8):
            state = state * 2862933555777941757 + 3037000493
            cp = (state >> 21) % 0x30000
            text += chr(cp)
        add(text)
    # Long strings, and the edges: empty, a lone mark, a blocked composition, a starter after
    # marks, an unpaired surrogate at either end.
    add("")
    add("\u0301")
    add("A\u0301\u0327")
    add("A\u0327\u0301")
    add("\u0301a")
    add("a\u0301" * 2000)
    add("\uD800")
    add("\uDC00")
    add("a\uD800b")
    add("a\uDC00\u0301b")
    add("\U0001D15E\U0001D165")
    return out, units


def main() -> None:
    decompositions = canonical_decompositions()
    compositions = primary_composites(decompositions)
    combining = combining_runs()

    # The tables are the whole point: check them the way the port reads them, then against
    # Python's normalizer on every case.
    assert decompositions == sorted(decompositions)
    assert compositions == sorted(compositions)
    assert combining == sorted(combining)
    for cp, first, second in decompositions:
        assert unicodedata.decomposition(chr(cp)).split()[0] == f"{first:04X}"
    record, surrogates = cases(decompositions, compositions)

    print(f"unidata_version {unicodedata.unidata_version}")
    print(f"  {len(decompositions)} decompositions, {len(compositions)} composites, "
          f"{len(combining)} combining runs, {len(record)} cases, "
          f"{len(surrogates)} surrogate cases")

    write_cs(decompositions, compositions, combining)
    print(f"wrote {OUT_CS}")

    fixture = {
        "note": __doc__.strip().splitlines()[0],
        "unidata_version": unicodedata.unidata_version,
        # [[input, NFC(input)], ...]
        "cases": record,
        # [[[input code points], [NFC(input) code points]], ...]: a lone surrogate is not a
        # JSON string .NET will read back.
        "surrogates": surrogates,
    }
    text = json.dumps(fixture, ensure_ascii=True, indent=1)
    OUT_JSON.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT_JSON}: {len(text)} bytes")


if __name__ == "__main__":
    main()
