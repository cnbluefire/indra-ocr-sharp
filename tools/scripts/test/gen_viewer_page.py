"""Write the viewer's page into the port: the assets, and the fixture the C# test reads.

``viewer.PAGE`` is 22 kB of HTML/CSS/JS and ``viewer.LOGO`` an 8 kB base64 PNG.  Retyping them
would be one typo away from a broken page, so both are taken from the reference module itself:

  src/Indra.Ocr.Viewer/ViewerPageAssets.Generated.cs   the two strings, as C# literals
  src/Indra.Ocr.Tests/fixtures/viewer_page.html        the answer ``GET /`` gives

    tools\\\\pyenv\\\\Scripts\\\\python.exe tools\\\\scripts\\\\test\\\\gen_viewer_page.py
"""

from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
SOURCE = ROOT / "src" / "Indra.Ocr.Viewer" / "ViewerPageAssets.Generated.cs"
FIXTURE = ROOT / "src" / "Indra.Ocr.Tests" / "fixtures" / "viewer_page.html"

#: The page goes in as a raw string literal whose closing delimiter sits at column 0, so the
#: compiler strips nothing and the content is taken verbatim.  (The page has no empty, blank or
#: trailing-space line and no ``\"\"\"``, which is what keeps that possible.)  CPython normalises
#: the line endings inside string literals, so the reference's page is always LF — and so is this.
HEADER = '''// <auto-generated>
//   Generated by tools/scripts/test/gen_viewer_page.py from the reference module
//   (resources/indra-src/indra_ocr/viewer.py).  Do not edit by hand: re-run the script.
// </auto-generated>

namespace Indra.Ocr.Viewer;

/// <summary>
/// <c>viewer.PAGE</c> and <c>viewer.LOGO</c>, exactly as the reference spells them.
/// </summary>
/// <remarks>
/// The page is a raw string in the reference's own source file and the logo the Datalab mark as
/// base64; the generator takes both from the module rather than retyping them.  CPython
/// normalises the line endings inside string literals, so the page the reference serves always
/// has LF endings — and so has this one, whatever a checkout did to this file.
/// </remarks>
internal static class ViewerPageAssets
{
    /// <summary><c>viewer.PAGE</c>: the page the browser loads, with <c>__LOGO__</c> where the
    /// header's mark goes.</summary>
    internal const string Page = """
'''

FOOTER = '''""";

    /// <summary><c>viewer.LOGO</c>: the Datalab mark, base64 PNG.</summary>
    internal const string Logo =
'''


def chunks(text: str, size: int = 96) -> str:
    """The text as C# string literals, concatenated — the way the reference wraps its own."""
    parts = [text[i : i + size] for i in range(0, len(text), size)]
    return " +\n".join(f'        "{part}"' for part in parts)


def main() -> None:
    from indra_ocr.viewer import LOGO, PAGE

    page = PAGE.replace("\r\n", "\n").replace("\r", "\n")
    # The closing delimiter has to sit on a line of its own; the newline before it is not part of
    # the content, so the page keeps its exact ending.
    SOURCE.write_text(HEADER + page + "\n" + FOOTER + chunks(LOGO) + ";\n}\n",
                      encoding="utf-8", newline="\n")
    FIXTURE.write_text(page.replace("__LOGO__", LOGO), encoding="utf-8", newline="\n")
    print(f"wrote {SOURCE.relative_to(ROOT)} ({SOURCE.stat().st_size} bytes)")
    print(f"wrote {FIXTURE.relative_to(ROOT)} ({FIXTURE.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
