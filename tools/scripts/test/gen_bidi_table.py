"""Generate the bidirectional-class table (step 145) from Python's ``unicodedata``.

``indra_ocr/document.py`` asks ``unicodedata.bidirectional`` for the class of every
single-code-point token, so the port must answer exactly as CPython does — including the empty
string for unassigned code points, and the classes CPython's UCD version defines.

The table is stored as contiguous ranges of equal class (a couple of thousand), which is both
compact and checkable: this generator verifies that the ranges reproduce Python's answer for
all 0x110000 code points, writes them into ``BidiClasses.cs``, and records them in
``fixtures/bidi.json`` so the C# port is checked exhaustively against them.

Run with the reference environment:

    tools\\pyenv\\Scripts\\python.exe tools\\scripts\\test\\gen_bidi_table.py
"""

from __future__ import annotations

import bisect
import json
import unicodedata
from pathlib import Path

OUT_CS = Path("src/Indra.Ocr.Core/Text/BidiClasses.cs")
OUT_JSON = Path("src/Indra.Ocr.Tests/fixtures/bidi.json")
MAX = 0x10FFFF


def build_ranges() -> list[tuple[int, int, str]]:
    """(start, end, class) runs covering every code point."""
    ranges: list[tuple[int, int, str]] = []
    previous: str | None = None
    start = 0
    for cp in range(MAX + 1):
        cls = unicodedata.bidirectional(chr(cp))
        if cls != previous:
            if previous is not None:
                ranges.append((start, cp - 1, previous))
            previous = cls
            start = cp
    ranges.append((start, MAX, previous))
    return ranges


def classify(ranges: list[tuple[int, int, str]], ends: list[int], cp: int) -> str:
    return ranges[bisect.bisect_left(ends, cp)][2]


def write_cs(ranges: list[tuple[int, int, str]]) -> None:
    lines = [
        "// <auto-generated>",
        "//     Generated by tools/scripts/test/gen_bidi_table.py from Python's unicodedata",
        f"//     (Unicode {unicodedata.unidata_version}).  Do not edit by hand:",
        "//     re-run the generator instead.",
        "// </auto-generated>",
        "",
        "namespace Indra.Ocr.Text;",
        "",
        "/// <summary>",
        "/// The Unicode bidirectional class of every code point, exactly as",
        "/// <c>unicodedata.bidirectional</c> reports it (an empty string for unassigned code",
        "/// points), stored as contiguous ranges of equal class.",
        "/// </summary>",
        "internal static class BidiClassData",
        "{",
        "    /// <summary>",
        "    /// Contiguous ranges in code point order, starting at U+0000:",
        "    /// <c>(last code point of the range, class)</c>.",
        "    /// </summary>",
        "    internal static readonly (int End, string Class)[] Ranges =",
        "    [",
    ]
    lines += [f'        (0x{end:04X}, "{cls}"),' for _, end, cls in ranges]
    lines += ["    ];", "}", ""]
    OUT_CS.write_text("\n".join(lines), encoding="utf-8", newline="\n")


def main() -> None:
    ranges = build_ranges()
    ends = [end for _, end, _ in ranges]

    # The ranges are the whole point: check them against Python for every code point.
    for cp in range(MAX + 1):
        assert classify(ranges, ends, cp) == unicodedata.bidirectional(chr(cp)), hex(cp)
    classes = sorted({cls for _, _, cls in ranges})
    print(f"unidata_version {unicodedata.unidata_version}")
    print(f"  {len(ranges)} ranges, {len(classes)} classes: {' '.join(repr(c) for c in classes)}")

    write_cs(ranges)
    print(f"wrote {OUT_CS}")

    fixture = {
        "note": __doc__.strip().splitlines()[0],
        "unidata_version": unicodedata.unidata_version,
        # [[last code point of the range, class], ...], contiguous from U+0000.
        "ranges": [[end, cls] for _, end, cls in ranges],
    }
    text = json.dumps(fixture, ensure_ascii=True, indent=1)
    OUT_JSON.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT_JSON}: {len(text)} bytes")


if __name__ == "__main__":
    main()
